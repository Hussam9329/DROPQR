// Pages that exist only in English (legal, admin) set <html data-force-lang="en">.
const LANG = document.documentElement.dataset.forceLang || (() => {
  try {
    const saved = localStorage.getItem('dropqr:lang');
    if (saved === 'ar' || saved === 'en') return saved;
  } catch {}
  return /^ar\b/i.test(navigator.language || '') ? 'ar' : 'en';
})();

document.documentElement.lang = LANG;
document.documentElement.dir = LANG === 'ar' ? 'rtl' : 'ltr';

function t(key, vars = {}) {
  const text = STRINGS[LANG][key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

// A server error in the visitor's language (falls back to the server's English text).
function errorText(data, fallbackKey) {
  if (data && data.code && STRINGS.en[`err_${data.code}`]) return t(`err_${data.code}`, data);
  return (data && data.error) || t(fallbackKey);
}

// Fills every [data-i18n] element, and [data-i18n-attr="attr:key"] attributes.
function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    for (const pair of el.dataset.i18nAttr.split(',')) {
      const [attr, key] = pair.split(':');
      el.setAttribute(attr.trim(), t(key.trim()));
    }
  });
}

// "5 downloads" / "25 downloads": Arabic uses a different word form above 10.
function countText(n, one, few, many) {
  return n === 1 ? t(one) : t(n > 10 ? many : few, { n });
}

function setLang(lang) {
  try { localStorage.setItem('dropqr:lang', lang); } catch {}
  location.reload();
}
